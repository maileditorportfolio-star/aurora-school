'use client';

import { useEffect, useState } from 'react';
import { Wallet, Receipt, CheckCircle2, AlertCircle, PhoneCall } from 'lucide-react';
import { api } from '@/lib/api';
import type { FeeInvoice } from '@/types';
import { ConsoleHeader, Panel, StatCard, EmptyState } from '@/components/ui/console';
import { PortalChildSelect, usePortalChild } from '@/components/portal-child';
import { useSchoolSettings } from '@/components/providers/school-settings';
import { cn, formatCurrency, formatDate } from '@/lib/utils';

const STATUS_STYLES: Record<FeeInvoice['status'], string> = {
  PENDING: 'bg-signal-100 text-signal-800',
  PARTIAL: 'bg-orange-100 text-orange-800',
  PAID: 'bg-emerald-50 text-emerald-700',
  OVERDUE: 'bg-rose-100 text-rose-700',
  WAIVED: 'bg-ink-100 text-ink-500',
};

export default function PortalFeesPage() {
  const { selected, loading: childLoading } = usePortalChild();
  const { settings } = useSchoolSettings();
  const [invoices, setInvoices] = useState<FeeInvoice[]>([]);
  const [totals, setTotals] = useState({ billed: 0, paid: 0, due: 0 });
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!selected) return;
    Promise.resolve().then(() => {
      setLoading(true);
      api.portal
        .fees({ studentId: selected.id })
        .then(({ invoices, totals }) => {
          setInvoices(invoices);
          setTotals(totals);
        })
        .finally(() => setLoading(false));
    });
  }, [selected]);

  return (
    <>
      <ConsoleHeader
        title="Fees & receipts"
        description="Every invoice and payment for your child. To pay, visit the office or send bKash and keep the transaction ID."
        actions={<PortalChildSelect />}
      />

      <div className="space-y-5 p-5 sm:p-8">
        <div className="grid gap-4 sm:grid-cols-3">
          <StatCard
            label="Total billed"
            value={formatCurrency(totals.billed)}
            icon={Receipt}
            tone="ink"
          />
          <StatCard
            label="Paid"
            value={formatCurrency(totals.paid)}
            icon={CheckCircle2}
            tone="brand"
          />
          <StatCard
            label="Outstanding"
            value={formatCurrency(totals.due)}
            icon={Wallet}
            tone={totals.due > 0 ? 'danger' : 'brand'}
          />
        </div>

        <div className="flex items-start gap-3 rounded-3xl border border-brand-100 bg-brand-50/60 p-4 text-xs leading-6 text-brand-900">
          <PhoneCall className="mt-0.5 h-4 w-4 shrink-0" aria-hidden />
          <p>
            To pay: cash at the school office (Sun–Thu, 8:00–14:00), or bKash to{' '}
            <span className="font-semibold">{settings.phone}</span> with the student’s admission
            number as reference. Receipts are issued same-day. Questions: {settings.email}.
          </p>
        </div>

        {childLoading || loading ? (
          <div className="h-64 animate-pulse rounded-3xl bg-ink-100" />
        ) : invoices.length === 0 ? (
          <EmptyState
            icon={Receipt}
            title="No invoices yet"
            hint="Invoices appear here each month once generated by the office."
          />
        ) : (
          <Panel title={`Invoices (${invoices.length})`}>
            <div className="overflow-x-auto">
              <table className="w-full min-w-[680px] text-sm">
                <thead>
                  <tr className="text-left text-[10px] uppercase tracking-[0.18em] text-ink-400">
                    <th className="pb-3 pe-3">Invoice</th>
                    <th className="pb-3 pe-3">For</th>
                    <th className="pb-3 pe-3">Due date</th>
                    <th className="pb-3 pe-3 text-right">Amount</th>
                    <th className="pb-3 pe-3 text-right">Balance</th>
                    <th className="pb-3">Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-ink-100">
                  {invoices.map((invoice) => {
                    const balance = invoice.amount - invoice.paidAmount;
                    return (
                      <tr key={invoice.id}>
                        <td className="py-2.5 pe-3">
                          <span className="font-mono text-xs text-ink-500">
                            {invoice.invoiceNo}
                          </span>
                          {invoice.payments && invoice.payments.length > 0 && (
                            <span className="block text-[9px] text-emerald-700">
                              {invoice.payments.length} payment(s) recorded
                            </span>
                          )}
                        </td>
                        <td className="py-2.5 pe-3 max-w-48">{invoice.title}</td>
                        <td className="py-2.5 pe-3 text-ink-500">{formatDate(invoice.dueDate)}</td>
                        <td className="py-2.5 pe-3 text-right tabular-nums">
                          {formatCurrency(invoice.amount)}
                        </td>
                        <td className="py-2.5 pe-3 text-right font-semibold tabular-nums">
                          {formatCurrency(balance)}
                        </td>
                        <td className="py-2.5">
                          <span
                            className={cn(
                              'rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider',
                              STATUS_STYLES[invoice.status],
                              invoice.isOverdue && 'bg-rose-100 text-rose-700',
                            )}
                          >
                            {invoice.isOverdue ? 'Overdue' : invoice.status}
                          </span>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>

            {invoices.some((i) => i.payments && i.payments.length > 0) && (
              <div className="mt-5 border-t border-ink-100 pt-4">
                <p className="flex items-center gap-2 text-[10px] font-bold uppercase tracking-[0.2em] text-ink-400">
                  <AlertCircle className="h-4 w-4" aria-hidden />
                  Payment history
                </p>
                <ul className="mt-2 divide-y divide-ink-100">
                  {invoices.flatMap((invoice) =>
                    (invoice.payments ?? []).map((payment) => (
                      <li
                        key={payment.id}
                        className="flex flex-wrap items-center justify-between gap-2 py-2 text-xs"
                      >
                        <span className="text-ink-600">
                          {eventLabel(invoice.title)} — {payment.method}
                          {payment.reference ? ` · ${payment.reference}` : ''}
                        </span>
                        <span className="flex items-center gap-3">
                          <span className="text-ink-400">{formatDate(payment.createdAt)}</span>
                          <span className="font-semibold text-emerald-700">
                            {formatCurrency(payment.amount)}
                          </span>
                        </span>
                      </li>
                    )),
                  )}
                </ul>
              </div>
            )}
          </Panel>
        )}
      </div>
    </>
  );
}

const eventLabel = (title: string) => (title.length > 40 ? `${title.slice(0, 40)}…` : title);
